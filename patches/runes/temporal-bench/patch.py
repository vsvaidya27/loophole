"""Tightened grader for runes/temporal-bench.

Generated by the reward audit's repairer (harden/audit). It loads the installed
environment unchanged and wraps its reward: after the original reward is computed,
tighten() decides the final reward from the response's final answer.

The grader now uses a strict whole-response check that matches the audit's ground-truth rule and the system prompt's 'letter only' instruction. It first removes <think> blocks and markdown emphasis. The remaining response must then be a single non-empty line holding exactly one answer letter. Accepted forms are a bare letter, (X), [X] or \boxed{X}, optionally preceded by 'Answer:', 'The answer is', 'Final answer:' or 'option'. A trailing period is allowed, and the letter is uppercased. Any extra text is rejected with 0.0: trailing option text, a reasoning line before the letter, or a second line that names another option (lowercase letters and spelled-out words included). A letter that differs from the normalized gold also scores 0.0. Responses that pass keep their original reward unchanged. This closes every listed false positive, old and new. The bare-letter reference and model answers still pass, but reasoning followed by the letter (on the next line or in the same line) now scores 0, even when the letter is correct. That trade-off was chosen because the grader has no access to the option text, so it cannot tell sound reasoning from wrong reasoning.
"""

# ---- tightening rules (written by the repairer) ----

import re

_PREFIX = r"(?:(?:the\s+)?(?:final\s+|correct\s+|best\s+)?answer(?:\s+is)?\s*[:\-]?\s*)?(?:(?:option|choice)\s*[:\-]?\s*)?"

_LETTER_FORMS = (
    r"\$?\\boxed\{\s*[\(\[]?\s*([A-Ha-h])\s*[\)\]]?\s*\}\$?",
    r"[\(\[]?\s*([A-Ha-h])\s*[\)\]]?",
)


def _clean(text):
    t = text or ""
    t = re.sub(r"(?s)<think>.*?</think>", " ", t)
    t = t.replace("**", "").replace("__", "").replace("`", "")
    return t.strip()


def _extract(text):
    t = _clean(text)
    if not t:
        return None
    lines = [l for l in t.splitlines() if l.strip()]
    if len(lines) != 1:
        return None
    s = lines[0].strip()
    s = re.sub(r"[\s\.!]+$", "", s).strip()
    if not s:
        return None
    for form in _LETTER_FORMS:
        m = re.fullmatch("(?i:" + _PREFIX + ")" + form, s)
        if m:
            return m.group(1).upper()
    return None


def tighten(text, gold, info, reward):
    g = (gold or "").strip().upper()
    gm = re.fullmatch(r"[\(\[]?\s*([A-Z])\s*[\)\]]?\.?", g)
    if gm:
        g = gm.group(1)
    ans = _extract(text if isinstance(text, str) else str(text or ""))
    if ans is None or ans != g:
        return 0.0
    return reward


# ---- wrapper (fixed template) ----

import functools
import json

import verifiers as vf

LOAD_ID = 'temporal-bench'


def _last_text(completion):
    if isinstance(completion, str):
        return completion
    for message in reversed(completion or []):
        get = message.get if isinstance(message, dict) else lambda key, m=message: getattr(m, key, None)
        if get("role") == "assistant":
            content = get("content")
            return content if isinstance(content, str) else ("" if content is None else str(content))
    return ""


def _gold(env, state):
    answer = state.get("answer")
    return "" if answer is None else str(answer)


def _info(state):
    info = state.get("info") or {}
    if isinstance(info, str):
        try:
            info = json.loads(info)
        except ValueError:
            info = {}
    return info if isinstance(info, dict) else {}


def _apply(env, states):
    for state in states:
        reward = float(state.get("reward") or 0.0)
        state["reward"] = float(tighten(_last_text(state.get("completion")), _gold(env, state), _info(state), reward))
    if states:
        mean = sum(s["reward"] for s in states) / len(states)
        for state in states:
            if "advantage" in state:
                state["advantage"] = state["reward"] - mean
            for step in state.get("trajectory") or []:
                if isinstance(step, dict):
                    step["reward"] = state["reward"]
                    if "advantage" in state:
                        step["advantage"] = state["advantage"]


def load_patched(**env_args):
    env = vf.load_environment(LOAD_ID, **env_args)
    rubric = env.rubric
    score_group, score_rollout = rubric.score_group, rubric.score_rollout

    @functools.wraps(score_group)
    async def tightened_group(states, *args, **kwargs):
        await score_group(states, *args, **kwargs)
        _apply(env, states)

    @functools.wraps(score_rollout)
    async def tightened_rollout(state, *args, **kwargs):
        await score_rollout(state, *args, **kwargs)
        _apply(env, [state])

    rubric.score_group = tightened_group
    rubric.score_rollout = tightened_rollout
    return env
