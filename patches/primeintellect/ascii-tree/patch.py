"""Tightened grader for primeintellect/ascii-tree.

Generated by the reward audit's repairer (harden/audit). It loads the installed
environment unchanged and wraps its reward: after the original reward is computed,
tighten() decides the final reward from the response's final answer.

Extract every <ascii_formatted>...</ascii_formatted> block from the final message; there must be at least one, and every block (first, middle and last) must contain no nested tags and, after stripping, splitting on '\n' only (as the original rewards do, so a bare carriage return is no longer turned into a line break and any remaining '\r' inside a line fails) and rstripping each line, must equal the gold tree normalized the same way. Otherwise the reward is 0.0; passing responses keep their original reward unchanged.
"""

# ---- tightening rules (written by the repairer) ----

import re as _re

_OPEN = "<ascii_formatted>"
_CLOSE = "</ascii_formatted>"
_PATTERN = _re.compile(r"<ascii_formatted>\s*(.*?)\s*</ascii_formatted>", _re.DOTALL)


def _blocks(text):
    if not isinstance(text, str):
        return []
    return [m.group(1) for m in _PATTERN.finditer(text)]


def _norm_lines(block):
    if block is None:
        return None
    # Split on '\n' only, exactly like the original rewards; a bare '\r'
    # inside a line is NOT treated as a line break. rstrip removes a
    # trailing '\r' from CRLF endings and trailing spaces.
    return [line.rstrip() for line in block.strip().split("\n")]


def _block_ok(block, gold_lines):
    if block is None:
        return False
    if _OPEN in block or _CLOSE in block:
        return False
    lines = _norm_lines(block)
    if not lines or lines == [""]:
        return False
    for line in lines:
        if "\r" in line:
            return False
    return lines == gold_lines


def tighten(text, gold, info, reward):
    gold_lines = _norm_lines(gold or "")
    if not gold_lines or gold_lines == [""]:
        return reward
    blocks = _blocks(text)
    if not blocks:
        return 0.0
    # Every answer block must be exactly the gold tree: no alternative or
    # hedged trees anywhere (first, middle or last).
    for block in blocks:
        if not _block_ok(block, gold_lines):
            return 0.0
    return reward


# ---- wrapper (fixed template) ----

import functools
import json

import verifiers as vf

LOAD_ID = 'ascii-tree'


def _last_text(completion):
    if isinstance(completion, str):
        return completion
    for message in reversed(completion or []):
        get = message.get if isinstance(message, dict) else lambda key, m=message: getattr(m, key, None)
        if get("role") == "assistant":
            content = get("content")
            return content if isinstance(content, str) else ("" if content is None else str(content))
    return ""


def _gold(env, state):
    answer = state.get("answer")
    return "" if answer is None else str(answer)


def _info(state):
    info = state.get("info") or {}
    if isinstance(info, str):
        try:
            info = json.loads(info)
        except ValueError:
            info = {}
    return info if isinstance(info, dict) else {}


def _apply(env, states):
    for state in states:
        reward = float(state.get("reward") or 0.0)
        state["reward"] = float(tighten(_last_text(state.get("completion")), _gold(env, state), _info(state), reward))
    if states:
        mean = sum(s["reward"] for s in states) / len(states)
        for state in states:
            if "advantage" in state:
                state["advantage"] = state["reward"] - mean
            for step in state.get("trajectory") or []:
                if isinstance(step, dict):
                    step["reward"] = state["reward"]
                    if "advantage" in state:
                        step["advantage"] = state["advantage"]


def load_patched(**env_args):
    env = vf.load_environment(LOAD_ID, **env_args)
    rubric = env.rubric
    score_group, score_rollout = rubric.score_group, rubric.score_rollout

    @functools.wraps(score_group)
    async def tightened_group(states, *args, **kwargs):
        await score_group(states, *args, **kwargs)
        _apply(env, states)

    @functools.wraps(score_rollout)
    async def tightened_rollout(state, *args, **kwargs):
        await score_rollout(state, *args, **kwargs)
        _apply(env, [state])

    rubric.score_group = tightened_group
    rubric.score_rollout = tightened_rollout
    return env
