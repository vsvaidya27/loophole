"""Tightened grader for primeintellect/deepscaler-math.

Generated by the reward audit's repairer (harden/audit). It loads the installed
environment unchanged and wraps its reward: after the original reward is computed,
tighten() decides the final reward from the response's final answer.

All the earlier rules stay: extract the last balanced \boxed{}, normalize the LaTeX, and compare exactly (rational or arithmetic evaluation with sqrt and powers) against a rational or tuple gold. Near-miss literals and unboxed near-miss numbers still score 0. New rule: when the boxed answer is an equation chain (a top-level '=' that is not just a leading variable label, no top-level ',' or ';') and the gold has no '=', the response no longer gets credit only because math_verify compares the right-hand side. Every side before the last must be either a variable-like label (contains letters outside LaTeX commands) or evaluate exactly to the gold's value. The evaluator handles \frac, \sqrt, \pi, powers and implicit multiplication, so symbolic radical golds are covered. If a side fails this check the reward is 0. Otherwise the final right-hand side goes through the usual strict checks. Responses that pass every check keep their original reward unchanged.
"""

# ---- tightening rules (written by the repairer) ----

import math
import re
from fractions import Fraction

_NUM = r'[+-]?(?:\d+(?:\.\d+)?|\.\d+)'
_UNUM = r'(?:\d+(?:\.\d+)?|\.\d+)'
_TOL = Fraction(1, 1000)
_VAR = r'^[A-Za-z](?:_\{?\w+\}?)?='


def _last_boxed(text):
    start = text.rfind('\\boxed{')
    if start == -1:
        return None
    i = start + len('\\boxed{')
    depth = 1
    j = i
    while j < len(text):
        ch = text[j]
        if ch == '{':
            depth += 1
        elif ch == '}':
            depth -= 1
            if depth == 0:
                return text[i:j]
        j += 1
    return None


def _text_sub(m):
    inner = m.group(1).strip()
    if re.fullmatch(_NUM, inner):
        return inner
    return ''


def _unbrace(s):
    for _ in range(5):
        if len(s) >= 2 and s[0] == '{' and s[-1] == '}':
            s = s[1:-1]
        else:
            break
    return s


def _norm(s):
    s = s.strip()
    s = s.replace('$', '')
    s = s.replace('\\dfrac', '\\frac').replace('\\tfrac', '\\frac')
    s = s.replace('\\left', '').replace('\\right', '')
    s = re.sub(r'\\(?:text|mathrm|mbox|textbf|mathbf)\{([^{}]*)\}', _text_sub, s)
    for tok in ('\\,', '\\!', '\\;', '\\:', '\\ ', '~'):
        s = s.replace(tok, '')
    s = re.sub(r'\s+', '', s)
    s = s.replace('^{\\circ}', '').replace('^\\circ', '')
    s = s.rstrip('.')
    s = _unbrace(s)
    s = re.sub(_VAR, '', s)
    return s


def _frac(a):
    try:
        return Fraction(a)
    except (ValueError, ZeroDivisionError):
        return None


def _rational(s):
    if not s:
        return None
    m = re.fullmatch(r'([+-]?)\\frac\{(' + _NUM + r')\}\{(' + _NUM + r')\}', s)
    if m is None:
        m = re.fullmatch(r'([+-]?)\\frac(\d)(\d)', s)
    if m is None:
        m = re.fullmatch(r'([+-]?)(' + _NUM + r')/(' + _NUM + r')', s)
    if m is not None:
        a = _frac(m.group(2))
        b = _frac(m.group(3))
        if a is None or b is None or b == 0:
            return None
        v = a / b
        return -v if m.group(1) == '-' else v
    if re.fullmatch(_NUM, s):
        return _frac(s)
    return None


def _match_brace(s, i):
    depth = 0
    j = i
    while j < len(s):
        if s[j] == '{':
            depth += 1
        elif s[j] == '}':
            depth -= 1
            if depth == 0:
                return j
        j += 1
    return -1


def _defrac(s):
    s = re.sub(r'\\frac(\d)(\d)', r'(\1)/(\2)', s)
    for _ in range(50):
        k = s.find('\\frac')
        if k == -1:
            break
        p = k + 5
        if p >= len(s) or s[p] != '{':
            return None
        e1 = _match_brace(s, p)
        if e1 == -1 or e1 + 1 >= len(s) or s[e1 + 1] != '{':
            return None
        e2 = _match_brace(s, e1 + 1)
        if e2 == -1:
            return None
        s = s[:k] + '((' + s[p + 1:e1] + ')/(' + s[e1 + 2:e2] + '))' + s[e2 + 1:]
    if '\\frac' in s:
        return None
    s = re.sub(r'\\sqrt(\d)', r'#(\1)', s)
    s = s.replace('\\sqrt{', '#{')
    if '\\sqrt' in s:
        return None
    s = s.replace('\\cdot', '*').replace('\\times', '*').replace('\\div', '/')
    s = s.replace('**', '^')
    s = s.replace('{', '(').replace('}', ')')
    return s


def _too_big(v):
    if isinstance(v, float):
        return (not math.isfinite(v)) or abs(v) > 1e300
    return v.numerator.bit_length() > 20000 or v.denominator.bit_length() > 20000


def _sqrt(v):
    if v < 0:
        return None
    if isinstance(v, Fraction):
        n, dd = v.numerator, v.denominator
        rn, rd = math.isqrt(n), math.isqrt(dd)
        if rn * rn == n and rd * rd == dd:
            return Fraction(rn, rd)
    try:
        return math.sqrt(float(v))
    except (OverflowError, ValueError):
        return None


class _P:
    def __init__(self, toks):
        self.t = toks
        self.i = 0

    def peek(self):
        return self.t[self.i] if self.i < len(self.t) else None

    def take(self):
        tok = self.peek()
        self.i += 1
        return tok

    def expr(self, d):
        if d > 80:
            return None
        v = self.term(d + 1)
        while v is not None and self.peek() in ('+', '-'):
            op = self.take()
            w = self.term(d + 1)
            if w is None:
                return None
            v = v + w if op == '+' else v - w
            if _too_big(v):
                return None
        return v

    def term(self, d):
        v = self.factor(d + 1)
        while v is not None and self.peek() in ('*', '/'):
            op = self.take()
            w = self.factor(d + 1)
            if w is None:
                return None
            if op == '*':
                v = v * w
            else:
                if w == 0:
                    return None
                v = v / w
            if _too_big(v):
                return None
        return v

    def factor(self, d):
        if d > 80:
            return None
        tok = self.peek()
        if tok is None:
            return None
        if tok in ('+', '-'):
            self.take()
            v = self.factor(d + 1)
            if v is None:
                return None
            return -v if tok == '-' else v
        return self.power(d + 1)

    def power(self, d):
        v = self.atom(d + 1)
        if v is None:
            return None
        if self.peek() == '^':
            self.take()
            e = self.factor(d + 1)
            if e is None or not isinstance(e, Fraction) or e.denominator != 1 or abs(e) > 64:
                return None
            if v == 0 and e < 0:
                return None
            try:
                v = v ** int(e)
            except (OverflowError, ZeroDivisionError):
                return None
            if _too_big(v):
                return None
        return v

    def atom(self, d):
        if d > 80:
            return None
        tok = self.peek()
        if tok is None:
            return None
        if tok == '#':
            self.take()
            v = self.atom(d + 1)
            if v is None:
                return None
            return _sqrt(v)
        if tok == 'p':
            self.take()
            return math.pi
        if tok == '(':
            self.take()
            v = self.expr(d + 1)
            if v is None or self.take() != ')':
                return None
            return v
        if re.fullmatch(_UNUM, tok):
            self.take()
            return _frac(tok)
        return None


def _arith(s):
    if not s or len(s) > 300:
        return None
    s = _defrac(s)
    if not s:
        return None
    toks = re.findall(r'\d+(?:\.\d+)?|\.\d+|[-+*/()^#]', s)
    if ''.join(toks) != s:
        return None
    p = _P(toks)
    v = p.expr(0)
    if v is None or p.i != len(toks):
        return None
    return v


def _numval(s):
    if not s or len(s) > 300:
        return None
    t = s.replace('\\pi', 'p')
    t = _defrac(t)
    if not t:
        return None
    toks = re.findall(r'\d+(?:\.\d+)?|\.\d+|[-+*/()^#p]', t)
    if ''.join(toks) != t:
        return None
    out = []
    for tok in toks:
        if out:
            prev = out[-1]
            prev_val = prev in (')', 'p') or re.fullmatch(_UNUM, prev) is not None
            cur_start = tok in ('(', '#', 'p') or re.fullmatch(_UNUM, tok) is not None
            if prev_val and cur_start:
                out.append('*')
        out.append(tok)
    p = _P(out)
    v = p.expr(0)
    if v is None or p.i != len(out):
        return None
    return v


def _val(s):
    v = _rational(s)
    if v is None:
        v = _arith(s)
    return v


def _eq(v, g):
    if isinstance(v, float) or isinstance(g, float):
        try:
            return abs(float(v) - float(g)) <= 1e-12 * max(1.0, abs(float(g)))
        except OverflowError:
            return False
    return v == g


def _near_miss(s, g):
    ag = abs(g)
    for lit in re.findall(_UNUM, s):
        v = _frac(lit)
        if v is None:
            continue
        if v != ag and abs(v - ag) <= _TOL * max(Fraction(1), ag):
            return True
    return False


def _close(v, g):
    return v != g and abs(v - g) <= _TOL * max(Fraction(1), abs(g))


def _wrapped(s, op, cl):
    if not (s.startswith(op) and s.endswith(cl)) or len(s) < len(op) + len(cl):
        return False
    depth = 0
    i = 0
    n = len(s)
    while i < n:
        if s.startswith('\\{', i) or s.startswith('\\}', i):
            depth += 1 if s[i + 1] == '{' else -1
            i += 2
        else:
            ch = s[i]
            if ch in '([{':
                depth += 1
            elif ch in ')]}':
                depth -= 1
            i += 1
        if depth == 0 and i < n:
            return False
    return depth == 0


def _strip_outer(s):
    for op, cl in (('\\{', '\\}'), ('(', ')'), ('[', ']')):
        if _wrapped(s, op, cl):
            return s[len(op):len(s) - len(cl)], op
    if len(s) >= 2 and s[0] in '([' and s[-1] in ')]':
        return s[1:-1], s[0]
    return s, ''


def _split_top(s):
    parts = []
    depth = 0
    cur = ''
    for ch in s:
        if ch in '([{':
            depth += 1
        elif ch in ')]}':
            depth -= 1
        if ch == ',' and depth == 0:
            parts.append(cur)
            cur = ''
        else:
            cur += ch
    parts.append(cur)
    return [_unbrace(re.sub(_VAR, '', _unbrace(p))) for p in parts]


def _split_char(s, sep):
    parts = []
    depth = 0
    cur = ''
    for ch in s:
        if ch in '([{':
            depth += 1
        elif ch in ')]}':
            depth -= 1
        if ch == sep and depth == 0:
            parts.append(cur)
            cur = ''
        else:
            cur += ch
    parts.append(cur)
    return parts


def _is_label(s):
    r = re.sub(r'\\[A-Za-z]+', '', s)
    return re.search(r'[A-Za-z]', r) is not None


def _eq_chain(box, gold):
    n = _norm(box)
    gn = _norm(gold)
    if '=' in gn or '=' not in n:
        return None, None
    if re.search(r'[<>!:]=|==', n):
        return None, None
    if len(_split_char(n, ',')) > 1 or len(_split_char(n, ';')) > 1:
        return None, None
    sides = [_unbrace(x) for x in _split_char(n, '=')]
    if len(sides) < 2 or any(not x for x in sides):
        return None, None
    gv = _val(gn)
    if gv is None:
        gv = _numval(gn)
    for side in sides[:-1]:
        if _is_label(side):
            continue
        v = _val(side)
        if v is None:
            v = _numval(side)
        if v is None:
            if gv is None and side == gn:
                continue
            return False, None
        if gv is None or not _eq(v, gv):
            return False, None
    return True, sides[-1]


def _gold_tuple(gold):
    n = _norm(gold)
    inner, br = _strip_outer(n)
    parts = _split_top(inner)
    if len(parts) < 2:
        return None, False
    vals = [_val(p) for p in parts]
    if any(v is None for v in vals):
        return None, False
    return vals, br in ('(', '[')


def _multiset_eq(vals, gvals):
    rest = list(gvals)
    for v in vals:
        hit = None
        for idx, g in enumerate(rest):
            if _eq(v, g):
                hit = idx
                break
        if hit is None:
            return False
        rest.pop(hit)
    return not rest


def _tighten_tuple(text, gvals, ordered, reward):
    box = _last_boxed(text)
    if box is None:
        nums = re.findall(_NUM, text)
        if len(nums) < len(gvals):
            return reward
        tail = [_frac(x) for x in nums[-len(gvals):]]
        for v in tail:
            if v is None:
                continue
            if any(_close(v, g) for g in gvals) and v not in gvals:
                return 0.0
        return reward
    bn = _norm(box)
    inner, _ = _strip_outer(bn)
    parts = _split_top(inner)
    if len(parts) != len(gvals):
        for g in gvals:
            if _near_miss(bn, g) and not any(_frac(l) == abs(g) for l in re.findall(_UNUM, bn)):
                return 0.0
        return reward
    vals = [_val(p) for p in parts]
    if all(v is not None for v in vals):
        if ordered:
            return reward if all(_eq(v, g) for v, g in zip(vals, gvals)) else 0.0
        return reward if _multiset_eq(vals, gvals) else 0.0
    for k, (p, v) in enumerate(zip(parts, vals)):
        targets = [gvals[k]] if ordered else gvals
        if v is not None:
            if not any(_eq(v, t) for t in targets):
                return 0.0
            continue
        for g in targets:
            if _near_miss(p, g):
                return 0.0
    return reward


def tighten(text, gold, info, reward):
    if reward <= 0:
        return reward
    text = text or ''
    gold = gold or ''
    if '%' in gold:
        return reward
    box0 = _last_boxed(text)
    if box0 is not None:
        status, rhs = _eq_chain(box0, gold)
        if status is False:
            return 0.0
        if status is True:
            text = '\\boxed{' + rhs + '}'
    g = _rational(_norm(gold))
    if g is None:
        gvals, ordered = _gold_tuple(gold)
        if gvals is not None:
            return _tighten_tuple(text, gvals, ordered, reward)
        return reward
    box = _last_boxed(text)
    if box is not None:
        n = _norm(box)
        if '%' in box:
            return 0.0 if _near_miss(n, g) else reward
        a = _val(n)
        if a is not None:
            return reward if _eq(a, g) else 0.0
        if _near_miss(n, g):
            return 0.0
        return reward
    nums = re.findall(_NUM, text)
    if not nums:
        return reward
    last = _frac(nums[-1])
    if last is None:
        return reward
    if _close(last, g):
        return 0.0
    return reward


