"""Tightened grader for metavind/mini-sudoku.

Generated by the reward audit's repairer (harden/audit). It loads the installed
environment unchanged and wraps its reward: after the original reward is computed,
tighten() decides the final reward from the response's final answer.

The grader now scores only the last <answer> block, and the grid inside it must be strictly formatted. The block may contain only ASCII digits, spaces, tabs and real newlines (\n or \r\n). Rows are split on '\n' only, not splitlines(), so form-feed, record-separator and Unicode line-break tricks are rejected. Cells within a row are split on spaces and tabs. The grid must be exactly 4 rows of 4 single digits from 1 to 4 and must equal the gold board, or the reward is 0.0. Otherwise the original reward is returned unchanged. The code uses only re.finditer and re.split with pattern strings and never calls compile().
"""

# ---- tightening rules (written by the repairer) ----

import re as _re

_ANSWER_PATTERN = r"<answer>\s*(.*?)\s*</answer>"
_ALLOWED_CHARS = set("1234567890 \t\r\n")


def _parse_grid(s):
    if s is None:
        return None
    s = str(s)
    # Only ASCII digits, ASCII spaces/tabs and real newlines are allowed;
    # exotic separators (form feed, record separator, unicode line breaks) are rejected.
    for ch in s:
        if ch not in _ALLOWED_CHARS:
            return None
    s = s.replace("\r\n", "\n")
    if "\r" in s:
        return None
    lines = [ln for ln in s.strip().split("\n") if ln.strip(" \t")]
    if len(lines) != 4:
        return None
    grid = []
    for ln in lines:
        cells = [c for c in _re.split(r"[ \t]+", ln.strip(" \t")) if c]
        if len(cells) != 4:
            return None
        row = []
        for c in cells:
            if len(c) != 1 or c not in "1234":
                return None
            row.append(int(c))
        grid.append(row)
    return grid


def _last_answer(text):
    last = None
    for m in _re.finditer(_ANSWER_PATTERN, text or "", _re.DOTALL):
        last = m.group(1)
    return last


def tighten(text, gold, info, reward):
    gold_grid = _parse_grid(gold)
    if gold_grid is None:
        return reward
    content = _last_answer(text)
    if content is None:
        return 0.0
    guess = _parse_grid(content)
    if guess is None or guess != gold_grid:
        return 0.0
    return reward


# ---- wrapper (fixed template) ----

import functools
import json

import verifiers as vf

LOAD_ID = 'mini-sudoku'


def _last_text(completion):
    if isinstance(completion, str):
        return completion
    for message in reversed(completion or []):
        get = message.get if isinstance(message, dict) else lambda key, m=message: getattr(m, key, None)
        if get("role") == "assistant":
            content = get("content")
            return content if isinstance(content, str) else ("" if content is None else str(content))
    return ""


def _gold(env, state):
    answer = state.get("answer")
    return "" if answer is None else str(answer)


def _info(state):
    info = state.get("info") or {}
    if isinstance(info, str):
        try:
            info = json.loads(info)
        except ValueError:
            info = {}
    return info if isinstance(info, dict) else {}


def _apply(env, states):
    for state in states:
        reward = float(state.get("reward") or 0.0)
        state["reward"] = float(tighten(_last_text(state.get("completion")), _gold(env, state), _info(state), reward))
    if states:
        mean = sum(s["reward"] for s in states) / len(states)
        for state in states:
            if "advantage" in state:
                state["advantage"] = state["reward"] - mean
            for step in state.get("trajectory") or []:
                if isinstance(step, dict):
                    step["reward"] = state["reward"]
                    if "advantage" in state:
                        step["advantage"] = state["advantage"]


def load_patched(**env_args):
    env = vf.load_environment(LOAD_ID, **env_args)
    rubric = env.rubric
    score_group, score_rollout = rubric.score_group, rubric.score_rollout

    @functools.wraps(score_group)
    async def tightened_group(states, *args, **kwargs):
        await score_group(states, *args, **kwargs)
        _apply(env, states)

    @functools.wraps(score_rollout)
    async def tightened_rollout(state, *args, **kwargs):
        await score_rollout(state, *args, **kwargs)
        _apply(env, [state])

    rubric.score_group = tightened_group
    rubric.score_rollout = tightened_rollout
    return env
