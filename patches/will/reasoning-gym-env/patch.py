"""Tightened grader for will/reasoning-gym-env.

Generated by the reward audit's repairer (harden/audit). It loads the installed
environment unchanged and wraps its reward: after the original reward is computed,
tighten() decides the final reward from the response's final answer.

Extracts every <answer>...</answer> block (and rejects responses with unclosed/extra <answer> tags). Each block, including the last, must consist only of whitespace-separated integer cells whose token list exactly equals the gold grid's tokens; otherwise the reward is 0. This closes the first-tag-wins multi-answer loophole and keeps the earlier fixes (no padding, hedge text, or comma separators). Passing responses keep their original reward.
"""

# ---- tightening rules (written by the repairer) ----

import re

_ANSWER_RE = re.compile(r"<answer>\s*(.*?)\s*</answer>", re.DOTALL)
_CELL_RE = re.compile(r"^-?\d+$")


def _blocks(text):
    if not isinstance(text, str):
        return None
    blocks = [m.group(1).strip() for m in _ANSWER_RE.finditer(text)]
    if not blocks:
        return None
    # Any stray/unclosed extra answer tag counts as a conflicting answer.
    if text.count("<answer>") != len(blocks):
        return None
    return blocks


def _tokens(s):
    # Split on whitespace only; punctuation such as commas stays attached
    # to tokens (or forms its own token) so it cannot silently vanish.
    return s.split()


def _matches(ans, gold_tokens):
    ans_tokens = _tokens(ans)
    if not ans_tokens:
        return False
    for tok in ans_tokens:
        if not _CELL_RE.match(tok):
            return False
    return ans_tokens == gold_tokens


def tighten(text, gold, info, reward):
    blocks = _blocks(text)
    if blocks is None:
        return 0.0
    gold_tokens = _tokens(str(gold))
    if not gold_tokens:
        return 0.0
    # Every <answer> block (in particular the final one) must be the gold grid;
    # a later conflicting answer cannot hide behind an earlier correct one.
    for ans in blocks:
        if not _matches(ans, gold_tokens):
            return 0.0
    return reward


# ---- wrapper (fixed template) ----

import functools
import json

import verifiers as vf

LOAD_ID = 'reasoning-gym-env'


def _last_text(completion):
    if isinstance(completion, str):
        return completion
    for message in reversed(completion or []):
        get = message.get if isinstance(message, dict) else lambda key, m=message: getattr(m, key, None)
        if get("role") == "assistant":
            content = get("content")
            return content if isinstance(content, str) else ("" if content is None else str(content))
    return ""


def _gold(env, state):
    answer = state.get("answer")
    return str(env.rg_dataset[int(answer)]["answer"])


def _info(state):
    info = state.get("info") or {}
    if isinstance(info, str):
        try:
            info = json.loads(info)
        except ValueError:
            info = {}
    return info if isinstance(info, dict) else {}


def _apply(env, states):
    for state in states:
        reward = float(state.get("reward") or 0.0)
        state["reward"] = float(tighten(_last_text(state.get("completion")), _gold(env, state), _info(state), reward))
    if states:
        mean = sum(s["reward"] for s in states) / len(states)
        for state in states:
            if "advantage" in state:
                state["advantage"] = state["reward"] - mean
            for step in state.get("trajectory") or []:
                if isinstance(step, dict):
                    step["reward"] = state["reward"]
                    if "advantage" in state:
                        step["advantage"] = state["advantage"]


def load_patched(**env_args):
    env = vf.load_environment(LOAD_ID, **env_args)
    rubric = env.rubric
    score_group, score_rollout = rubric.score_group, rubric.score_rollout

    @functools.wraps(score_group)
    async def tightened_group(states, *args, **kwargs):
        await score_group(states, *args, **kwargs)
        _apply(env, states)

    @functools.wraps(score_rollout)
    async def tightened_rollout(state, *args, **kwargs):
        await score_rollout(state, *args, **kwargs)
        _apply(env, [state])

    rubric.score_group = tightened_group
    rubric.score_rollout = tightened_rollout
    return env
