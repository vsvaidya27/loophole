"""Tightened grader for harleycooper/nanochatAquaRat.

Generated by the reward audit's repairer (harden/audit). It loads the installed
environment unchanged and wraps its reward: after the original reward is computed,
tighten() decides the final reward from the response's final answer.

The grade comes from the LAST 'Answer:' or 'Answer-' marker (case-insensitive, whitespace allowed around the separator). The character right after that marker must be a letter A-E. That letter must also stand alone: the next character cannot be word-like, using a Unicode-aware check that rejects any letter, digit, combining mark, underscore/connector punctuation, or format/private/unassigned character. This closes the 'A_', 'Aé' and 'D٣' bypasses. If the response has no marker, it is accepted only when it is a bare single letter, optionally wrapped in markdown or brackets. The extracted letter must equal the gold letter, otherwise the reward is 0.0. Passing responses keep their original reward. The code uses only module-level re functions and unicodedata, with no eval, exec or compile.
"""

# ---- tightening rules (written by the repairer) ----

import re
import unicodedata

_MARKER_PAT = r"(?i)answer\s*[:\-]\s*"
_LETTER_AFTER_PAT = r"([A-Ea-e])"
_BARE_PAT = r"[\s\*_\(\[]*([A-Ea-e])[\s\*_\)\]\.]*"
_VALID = {"A", "B", "C", "D", "E"}
_BAD_CATS = ("L", "M", "N", "Pc", "Cf", "Co", "Cn")


def _is_word_like(ch):
    if ch.isalnum() or ch == "_":
        return True
    cat = unicodedata.category(ch)
    return cat.startswith(_BAD_CATS)


def _final_letter(text):
    if not isinstance(text, str) or not text:
        return None
    last = None
    for m in re.finditer(_MARKER_PAT, text):
        last = m
    if last is not None:
        # The LAST answer marker decides; whatever follows must be a valid standalone letter.
        rest = text[last.end():]
        m2 = re.match(_LETTER_AFTER_PAT, rest)
        if not m2:
            return None
        nxt = rest[m2.end():m2.end() + 1]
        if nxt and _is_word_like(nxt):
            return None
        return m2.group(1).upper()
    m = re.fullmatch(_BARE_PAT, text)
    if m:
        return m.group(1).upper()
    return None


def tighten(text, gold, info, reward):
    g = (gold or "").strip().upper()
    if g not in _VALID:
        return reward
    letter = _final_letter(text)
    if letter is None or letter != g:
        return 0.0
    return reward


# ---- wrapper (fixed template) ----

import functools
import json

import verifiers as vf

LOAD_ID = 'nanochatAquaRat'


def _last_text(completion):
    if isinstance(completion, str):
        return completion
    for message in reversed(completion or []):
        get = message.get if isinstance(message, dict) else lambda key, m=message: getattr(m, key, None)
        if get("role") == "assistant":
            content = get("content")
            return content if isinstance(content, str) else ("" if content is None else str(content))
    return ""


def _gold(env, state):
    answer = state.get("answer")
    return "" if answer is None else str(answer)


def _info(state):
    info = state.get("info") or {}
    if isinstance(info, str):
        try:
            info = json.loads(info)
        except ValueError:
            info = {}
    return info if isinstance(info, dict) else {}


def _apply(env, states):
    for state in states:
        reward = float(state.get("reward") or 0.0)
        state["reward"] = float(tighten(_last_text(state.get("completion")), _gold(env, state), _info(state), reward))
    if states:
        mean = sum(s["reward"] for s in states) / len(states)
        for state in states:
            if "advantage" in state:
                state["advantage"] = state["reward"] - mean
            for step in state.get("trajectory") or []:
                if isinstance(step, dict):
                    step["reward"] = state["reward"]
                    if "advantage" in state:
                        step["advantage"] = state["advantage"]


def load_patched(**env_args):
    env = vf.load_environment(LOAD_ID, **env_args)
    rubric = env.rubric
    score_group, score_rollout = rubric.score_group, rubric.score_rollout

    @functools.wraps(score_group)
    async def tightened_group(states, *args, **kwargs):
        await score_group(states, *args, **kwargs)
        _apply(env, states)

    @functools.wraps(score_rollout)
    async def tightened_rollout(state, *args, **kwargs):
        await score_rollout(state, *args, **kwargs)
        _apply(env, [state])

    rubric.score_group = tightened_group
    rubric.score_rollout = tightened_rollout
    return env
