"""Tightened grader for beauduffy/ai2-arc.

Generated by the reward audit's repairer (harden/audit). It loads the installed
environment unchanged and wraps its reward: after the original reward is computed,
tighten() decides the final reward from the response's final answer.

The grader finds the last box command in the response. It must be \boxed or \fbox. It must sit at brace depth 0 under both brace-counting conventions: escape-aware, and naive, where every '{' and '}' counts as the original parser and the verifier count it. Its brace-matched content must close at the same position under both conventions. The content must contain no escaped braces and no nested box commands. After removing simple wrappers, parentheses and a trailing period, the content must uppercase to the gold label. A response with no box passes only if its whole text equals the gold label, and any other box command at all fails it. This closes the escaped-brace depth mismatch: a box opened before '\{' now leaves the later \boxed{X} at nonzero naive depth, so it is rejected. All earlier fixes are kept: no nested or alternate box commands, no spaced boxes, no optional-argument or colorbox skipping. Responses that pass return the original reward unchanged.
"""

# ---- tightening rules (written by the repairer) ----

_BOX_NAMES = ("boxed", "fbox", "framebox", "bbox", "fcolorbox", "colorbox", "ovalbox", "doublebox", "shadowbox", "Ovalbox", "mbox", "makebox", "parbox", "raisebox", "savebox", "sbox", "cfbox", "tcbox", "tcolorbox", "dboxed", "Boxed")
_PLAIN_FINAL = ("boxed", "fbox")
_WRAPPERS = ("\\text{", "\\textbf{", "\\mathrm{", "\\mathbf{", "\\textrm{", "{")


def _match_brace(text, open_idx, escaped=True):
    depth = 0
    n = len(text)
    k = open_idx
    while k < n:
        ch = text[k]
        if escaped and ch == "\\" and k + 1 < n and text[k + 1] in "{}":
            k += 2
            continue
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return k
        k += 1
    return -1


def _box_positions(text):
    out = []
    n = len(text)
    i = 0
    while True:
        j = text.find("\\", i)
        if j < 0:
            break
        k = j + 1
        while k < n and text[k].isalpha():
            k += 1
        name = text[j + 1:k]
        if name in _BOX_NAMES:
            out.append((j, k, name))
        i = j + 1
    return out


def _depth_before(text, pos, escaped=True):
    depth = 0
    k = 0
    while k < pos:
        ch = text[k]
        if escaped and ch == "\\" and k + 1 < pos and text[k + 1] in "{}":
            k += 2
            continue
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth = max(0, depth - 1)
        k += 1
    return depth


def _has_box_cmd(s):
    return bool(_box_positions(s)) or any(("\\" + nm) in s for nm in _BOX_NAMES)


def _normalize(s):
    s = s.strip()
    changed = True
    while changed:
        changed = False
        for w in _WRAPPERS:
            if s.startswith(w) and s.endswith("}") and _match_brace(s, len(w) - 1, False) == len(s) - 1 and _match_brace(s, len(w) - 1, True) == len(s) - 1:
                s = s[len(w):-1].strip()
                changed = True
                break
        if len(s) >= 2 and s[0] == "(" and s[-1] == ")":
            s = s[1:-1].strip()
            changed = True
        if s.endswith("."):
            s = s[:-1].strip()
            changed = True
    return s.upper()


def tighten(text, gold, info, reward):
    if reward <= 0:
        return reward
    text = text or ""
    g = (gold or "").strip().upper()
    if not g:
        return 0.0
    boxes = _box_positions(text)
    if not boxes:
        if any(("\\" + nm) in text for nm in _BOX_NAMES):
            return 0.0
        return reward if text.strip().upper() == g else 0.0
    start, name_end, name = boxes[-1]
    if name not in _PLAIN_FINAL:
        return 0.0
    if _depth_before(text, start, True) != 0 or _depth_before(text, start, False) != 0:
        return 0.0
    n = len(text)
    k = name_end
    while k < n and text[k].isspace():
        k += 1
    if k >= n or text[k] != "{":
        return 0.0
    end = _match_brace(text, k, False)
    end2 = _match_brace(text, k, True)
    if end < 0 or end != end2:
        return 0.0
    content = text[k + 1:end]
    if "\\{" in content or "\\}" in content:
        return 0.0
    if _has_box_cmd(content):
        return 0.0
    if _normalize(content) != g:
        return 0.0
    return reward


# ---- wrapper (fixed template) ----

import functools
import json

import verifiers as vf

LOAD_ID = 'ai2-arc'


def _last_text(completion):
    if isinstance(completion, str):
        return completion
    for message in reversed(completion or []):
        get = message.get if isinstance(message, dict) else lambda key, m=message: getattr(m, key, None)
        if get("role") == "assistant":
            content = get("content")
            return content if isinstance(content, str) else ("" if content is None else str(content))
    return ""


def _gold(env, state):
    answer = state.get("answer")
    return "" if answer is None else str(answer)


def _info(state):
    info = state.get("info") or {}
    if isinstance(info, str):
        try:
            info = json.loads(info)
        except ValueError:
            info = {}
    return info if isinstance(info, dict) else {}


def _apply(env, states):
    for state in states:
        reward = float(state.get("reward") or 0.0)
        state["reward"] = float(tighten(_last_text(state.get("completion")), _gold(env, state), _info(state), reward))
    if states:
        mean = sum(s["reward"] for s in states) / len(states)
        for state in states:
            if "advantage" in state:
                state["advantage"] = state["reward"] - mean
            for step in state.get("trajectory") or []:
                if isinstance(step, dict):
                    step["reward"] = state["reward"]
                    if "advantage" in state:
                        step["advantage"] = state["advantage"]


def load_patched(**env_args):
    env = vf.load_environment(LOAD_ID, **env_args)
    rubric = env.rubric
    score_group, score_rollout = rubric.score_group, rubric.score_rollout

    @functools.wraps(score_group)
    async def tightened_group(states, *args, **kwargs):
        await score_group(states, *args, **kwargs)
        _apply(env, states)

    @functools.wraps(score_rollout)
    async def tightened_rollout(state, *args, **kwargs):
        await score_rollout(state, *args, **kwargs)
        _apply(env, [state])

    rubric.score_group = tightened_group
    rubric.score_rollout = tightened_rollout
    return env
