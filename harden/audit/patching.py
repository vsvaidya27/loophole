"""Tightened-grader files: the fixed wrapper around the repairer's tighten() rules, and
the static checks a candidate must pass before it is scored."""

from __future__ import annotations

import ast
import re
import shutil
import tempfile
from pathlib import Path

from .common import ROOT, EnvSpec, ck

HEADER = '''"""Tightened grader for {env_id}.

Generated by the reward audit's repairer (harden/audit). It loads the installed
environment unchanged and wraps its reward: after the original reward is computed,
tighten() decides the final reward from the response's final answer.

{summary}
"""
'''

RULES_START = "# ---- tightening rules (written by the repairer) ----"
RULES_END = "# ---- wrapper (fixed template) ----"

LEGACY_WRAPPER = '''

import functools
import json

import verifiers as vf

LOAD_ID = {load_id!r}


def _last_text(completion):
    if isinstance(completion, str):
        return completion
    for message in reversed(completion or []):
        get = message.get if isinstance(message, dict) else lambda key, m=message: getattr(m, key, None)
        if get("role") == "assistant":
            content = get("content")
            return content if isinstance(content, str) else ("" if content is None else str(content))
    return ""


def _gold(env, state):
    answer = state.get("answer")
{gold_body}


def _info(state):
    info = state.get("info") or {{}}
    if isinstance(info, str):
        try:
            info = json.loads(info)
        except ValueError:
            info = {{}}
    return info if isinstance(info, dict) else {{}}


def _apply(env, states):
    for state in states:
        reward = float(state.get("reward") or 0.0)
        state["reward"] = float(tighten(_last_text(state.get("completion")), _gold(env, state), _info(state), reward))
    if states:
        mean = sum(s["reward"] for s in states) / len(states)
        for state in states:
            if "advantage" in state:
                state["advantage"] = state["reward"] - mean
            for step in state.get("trajectory") or []:
                if isinstance(step, dict):
                    step["reward"] = state["reward"]
                    if "advantage" in state:
                        step["advantage"] = state["advantage"]


def load_patched(**env_args):
    env = vf.load_environment(LOAD_ID, **env_args)
    rubric = env.rubric
    score_group, score_rollout = rubric.score_group, rubric.score_rollout

    @functools.wraps(score_group)
    async def tightened_group(states, *args, **kwargs):
        await score_group(states, *args, **kwargs)
        _apply(env, states)

    @functools.wraps(score_rollout)
    async def tightened_rollout(state, *args, **kwargs):
        await score_rollout(state, *args, **kwargs)
        _apply(env, [state])

    rubric.score_group = tightened_group
    rubric.score_rollout = tightened_rollout
    return env
'''

V1_WRAPPER = '''

import functools
import types

from verifiers.v1.utils.loaders import load_taskset, taskset_config_type

LOAD_ID = {load_id!r}
ANSWER_FIELD = {answer_field!r}


def _wrap_reward(fn, task):
    @functools.wraps(fn)
    async def tightened(*args, **kwargs):
        value = await fn(*args, **kwargs)
        trace = kwargs.get("trace", args[0] if args else None)
        text = (getattr(trace, "last_reply", "") or "") if trace is not None else ""
        return float(tighten(text, str(getattr(task.data, ANSWER_FIELD)), {{}}, float(value)))

    for key in ("reward", "reward_priority", "_vf_weight"):
        if hasattr(fn, key):
            setattr(tightened, key, getattr(fn, key))
    return tightened


def _tighten_task(task):
    hooks = type(task).hooks

    def tightened_hooks(self, attr):
        fns = hooks(self, attr)
        return [_wrap_reward(fn, self) for fn in fns] if attr == "reward" else fns

    task.hooks = types.MethodType(tightened_hooks, task)
    return task


def load_patched(**env_args):
    config = taskset_config_type(LOAD_ID).model_validate({{**env_args, "id": LOAD_ID}})
    taskset = load_taskset(config)
    return taskset.view(lambda tasks: (_tighten_task(task) for task in tasks))
'''


def gold_body(spec: EnvSpec) -> str:
    if spec.gold == "rg_dataset":
        return '    return str(env.rg_dataset[int(answer)]["answer"])'
    return '    return "" if answer is None else str(answer)'


def render(spec: EnvSpec, code: str, summary: str) -> str:
    summary = summary.replace('"""', "'''").strip()
    header = HEADER.format(env_id=spec.env_id, summary=summary)
    if spec.api == "legacy":
        wrapper = LEGACY_WRAPPER.format(load_id=spec.load_id, gold_body=gold_body(spec))
    else:
        wrapper = V1_WRAPPER.format(load_id=spec.load_id, answer_field=spec.answer_field or "answer")
    return f"{header}\n{RULES_START}\n\n{code.strip()}\n\n\n{RULES_END}{wrapper}"


def rules_of(source: str) -> str:
    """The repairer's part of a rendered patch file."""
    if RULES_START not in source:
        return source
    return source.split(RULES_START, 1)[1].split(RULES_END, 1)[0].strip()


def template_for_prompt(spec: EnvSpec) -> str:
    return render(spec, "def tighten(text, gold, info, reward):\n    ...  # your rules go here", "<one-paragraph summary of the rules>")

FORBIDDEN = [
    (r"\bopen\s*\(", "file access (open)"),
    (r"\bPath\s*\(", "file access (pathlib)"),
    (r"\bos\.", "the os module"),
    (r"\bsubprocess\b", "subprocess"),
    (r"\b(?:eval|exec)\s*\(", "eval/exec"),
    (r"__import__|importlib", "dynamic imports"),
    (r"\bsys\.path\b", "sys.path changes"),
    (r"\b(?:requests|urllib|socket|http)\b", "network access"),
]


def static_problems(spec: EnvSpec, code: str, exploit_attempts: list[dict]) -> list[str]:
    """Problems with the repairer's code, before anything runs."""
    problems = []
    try:
        tree = ast.parse(code)
    except SyntaxError as e:
        return [f"the code does not parse: {e}"]
    names = {n.name for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))}
    if "tighten" not in names:
        problems.append("the code must define tighten(text, gold, info, reward)")
    for node in tree.body:
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Import, ast.ImportFrom, ast.Assign, ast.AnnAssign, ast.Expr, ast.ClassDef)):
            problems.append(f"top-level statement {type(node).__name__} is not allowed (define functions and constants only)")
        if isinstance(node, ast.Expr) and not isinstance(getattr(node, "value", None), ast.Constant):
            problems.append("top-level expressions with side effects are not allowed")
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            module = node.module if isinstance(node, ast.ImportFrom) else node.names[0].name
            if module and module.split(".")[0] in ("harden", "scripts", "check_leaderboard"):
                problems.append(f"import of repository module {module!r} is not allowed")
    # Regex compilation is ordinary parsing, not Python code execution. Check
    # compile calls structurally so re.compile() does not trigger the builtin ban.
    regex_modules = {alias.asname or alias.name for node in ast.walk(tree) if isinstance(node, ast.Import)
                     for alias in node.names if alias.name == "re"}
    regex_functions = {alias.asname or alias.name for node in ast.walk(tree)
                       if isinstance(node, ast.ImportFrom) and node.module == "re"
                       for alias in node.names if alias.name == "compile"}
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        func = node.func
        if isinstance(func, ast.Name) and func.id == "compile" and func.id not in regex_functions:
            problems.append("uses Python compile(), which a tightened grader may not")
        elif (isinstance(func, ast.Attribute) and func.attr == "compile"
              and not (isinstance(func.value, ast.Name) and func.value.id in regex_modules)):
            problems.append("uses a non-regex compile(), which a tightened grader may not")
    stripped = _code_without_comments(code)
    for pattern, what in FORBIDDEN:
        if re.search(pattern, stripped):
            problems.append(f"uses {what}, which a tightened grader may not")
    with tempfile.TemporaryDirectory(prefix="audit-static-") as tmp:
        patch_dir = Path(tmp) / "patches" / spec.env_id
        patch_dir.mkdir(parents=True)
        (patch_dir / "patch.py").write_text(render(spec, code, "static check"))
        rep = ck.Report()
        ck.check_patch_dir(ROOT, {"env_id": spec.env_id}, patch_dir, exploit_attempts, rep, spec.env_id)
        problems += [f.split("] ", 1)[-1] for f in rep.failures]
    return problems


def _code_without_comments(code: str) -> str:
    with tempfile.NamedTemporaryFile("w", suffix=".py", delete=False) as handle:
        handle.write(code)
        path = Path(handle.name)
    try:
        return ck.patch_code(path)
    finally:
        path.unlink()


def write_candidate(spec: EnvSpec, code: str, summary: str, directory: Path) -> Path:
    if directory.exists():
        shutil.rmtree(directory)
    directory.mkdir(parents=True)
    (directory / "patch.py").write_text(render(spec, code, summary))
    return directory


def install(candidate_dir: Path, spec: EnvSpec) -> str:
    """Copy an accepted candidate to patches/<env_id>/ and return its patch_digest."""
    target = spec.patch_dir
    if target.exists():
        shutil.rmtree(target)
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(candidate_dir, target, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    return ck.patch_digest(target)
